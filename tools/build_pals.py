#!/usr/bin/env python3
"""
Turns every pal in Pals/<name>/ (front.gif + back.gif) into everything the app needs.
Run this FIRST in the build (before tools/make_fonts.py).

Add a new pal: make a folder Pals/<name>/ with
    front.gif   the pal facing you (art facing LEFT, like the Pokémon Black/White sprites)
    back.gif    the pal from behind (art facing RIGHT)
Optional Pals/<name>/pal.json: {"name": "Display Name", "frontFaces": "left", "backFaces": "right"}

Writes (all ignored by git, rebuilt every time):
    PalGen/PalFrames.xcassets   every unique frame, on one shared square canvas, feet on the bottom edge
    PalGen/PalSpriteData.swift  PalSpecies enum with frame order + timing
    PalGen/RoomPal.swift        the widget's "Pal" choice list
    PalGen/pal_frames.json      frame data for tools/build_room_fonts.py
    Sprites/<name>_1..10.png    10 idle frames for the Dynamic Island
"""
import hashlib
import json
import shutil
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
PALS = ROOT / "Pals"
OUT = ROOT / "PalGen"
CAT = OUT / "PalFrames.xcassets"
SPRITES = ROOT / "Sprites"
MIN_CANVAS = 68   # all pals share one canvas so they're drawn at the same pixel scale


def frames_of(gif):
    im = Image.open(gif)
    out = []
    for i in range(getattr(im, "n_frames", 1)):
        im.seek(i)
        out.append((im.convert("RGBA"), im.info.get("duration", 100) or 100))
    return out


def imageset(name, img):
    d = CAT / f"{name}.imageset"
    d.mkdir(parents=True)
    img.save(d / f"{name}.png")
    (d / "Contents.json").write_text(json.dumps({
        "images": [{"filename": f"{name}.png", "idiom": "universal"}],
        "info": {"version": 1, "author": "xcode"},
        "properties": {"compression-type": "lossless", "preserves-vector-representation": False}}, indent=2))


def swift_name(key):
    return "".join(c for c in key if c.isalnum()).lower() or "pal"


def main():
    shutil.rmtree(OUT, ignore_errors=True)
    CAT.mkdir(parents=True)
    (CAT / "Contents.json").write_text(json.dumps({"info": {"version": 1, "author": "xcode"}}))

    pals = []
    for d in sorted(p for p in PALS.iterdir() if p.is_dir()):
        if not (d / "front.gif").exists() or not (d / "back.gif").exists():
            print(f"  skipping {d.name}: needs front.gif and back.gif")
            continue
        meta = json.loads((d / "pal.json").read_text()) if (d / "pal.json").exists() else {}
        pals.append((swift_name(d.name), d, meta))
    if not pals:
        raise SystemExit("No pals found in Pals/")

    clips = {key: {c: frames_of(d / f"{c}.gif") for c in ("front", "back")} for key, d, _ in pals}
    canvas = max([MIN_CANVAS] + [max(f.width, f.height) for c in clips.values() for fr in c.values() for f, _ in fr])

    data = {}
    for key, d, meta in pals:
        data[key] = {"name": meta.get("name", d.name.capitalize())}
        for clip in ("front", "back"):
            seen, seq = {}, []
            for f, dur in clips[key][clip]:
                c = Image.new("RGBA", (canvas, canvas), (0, 0, 0, 0))
                c.alpha_composite(f, ((canvas - f.width) // 2, canvas - f.height))
                h = hashlib.md5(c.tobytes()).hexdigest()
                if h not in seen:
                    seen[h] = f"pal_{key}_{clip}_{len(seen):02d}"
                    imageset(seen[h], c)
                if seq and seq[-1][0] == seen[h]:
                    seq[-1][1] += dur
                else:
                    seq.append([seen[h], dur])
            faces = meta.get(f"{clip}Faces", "left" if clip == "front" else "right")
            data[key][clip] = {"naturalFacing": faces, "frames": [{"image": n, "ms": ms} for n, ms in seq]}
        print(f"  {key}: {len(data[key]['front']['frames'])} front / {len(data[key]['back']['frames'])} back steps")

        # 10 evenly spaced idle frames for the Dynamic Island (loops cleanly at 1 frame a second)
        for old in SPRITES.glob(f"{key}_*.png"):
            old.unlink()
        seq = data[key]["front"]["frames"]
        loop = sum(f["ms"] for f in seq)
        for i in range(10):
            t = i * loop / 10
            for f in seq:
                if t < f["ms"]:
                    name = f["image"]; break
                t -= f["ms"]
            Image.open(CAT / f"{name}.imageset" / f"{name}.png").save(SPRITES / f"{key}_{i + 1}.png")

    (OUT / "pal_frames.json").write_text(json.dumps(data))

    def clip_src(clip):
        rows = ",\n".join(f'            .init(image: "{f["image"]}", ms: {f["ms"]})' for f in clip["frames"])
        return f"PalClip(naturalFacing: .{clip['naturalFacing']}, frames: [\n{rows}\n        ])"

    keys = [k for k, _, _ in pals]
    swift = f"""// Generated by tools/build_pals.py from the Pals folder. Don't edit by hand.
import Foundation

enum PalFacing {{ case left, right }}

struct PalFrame {{
    let image: String
    let ms: Int
}}

struct PalClip {{
    /// Which way the artwork faces before any flipping.
    let naturalFacing: PalFacing
    let frames: [PalFrame]
    /// Every frame is {canvas}x{canvas} with the feet on the bottom edge, so all pals share one pixel scale.
    let size: Int = {canvas}
    var loopMs: Int {{ frames.reduce(0) {{ $0 + $1.ms }} }}

    /// Frame to show `t` seconds into the loop.
    func frame(at t: TimeInterval) -> PalFrame {{
        var ms = Int(t * 1000) % max(loopMs, 1)
        for f in frames {{
            if ms < f.ms {{ return f }}
            ms -= f.ms
        }}
        return frames[0]
    }}
}}

/// Canvas size of the pal frames, in sprite pixels.
let palCanvasSize: CGFloat = {canvas}

/// The pals you can pick from (one per folder in Pals/).
enum PalSpecies: String, CaseIterable, Identifiable, Codable {{
{chr(10).join(f"    case {k}" for k in keys)}

    var id: String {{ rawValue }}

    var displayName: String {{
        switch self {{
{chr(10).join(f'        case .{k}: "{data[k]["name"]}"' for k in keys)}
        }}
    }}

    var front: PalClip {{ Self.frontClips[self]! }}
    var back: PalClip {{ Self.backClips[self]! }}

    private static let frontClips: [PalSpecies: PalClip] = Dictionary(uniqueKeysWithValues: allCases.map {{ ($0, $0.makeFront()) }})
    private static let backClips: [PalSpecies: PalClip] = Dictionary(uniqueKeysWithValues: allCases.map {{ ($0, $0.makeBack()) }})

    private func makeFront() -> PalClip {{
        switch self {{
{chr(10).join(f"        case .{k}: {clip_src(data[k]['front'])}" for k in keys)}
        }}
    }}

    private func makeBack() -> PalClip {{
        switch self {{
{chr(10).join(f"        case .{k}: {clip_src(data[k]['back'])}" for k in keys)}
        }}
    }}
}}
"""
    (OUT / "PalSpriteData.swift").write_text(swift.replace("import Foundation", "import Foundation\nimport CoreGraphics"))

    room_pal = f"""// Generated by tools/build_pals.py. The widget's "Pal" choice list.
import AppIntents

enum RoomPal: String, AppEnum {{
{chr(10).join(f"    case {k}" for k in keys)}

    static var typeDisplayRepresentation: TypeDisplayRepresentation = "Pal"
    static var caseDisplayRepresentations: [RoomPal: DisplayRepresentation] = [
{chr(10).join(f'        .{k}: "{data[k]["name"]}",' for k in keys)}
    ]
    var species: PalSpecies {{ PalSpecies(rawValue: rawValue) ?? .{keys[0]} }}
}}
"""
    (OUT / "RoomPal.swift").write_text(room_pal)
    print(f"Done: {len(keys)} pal(s), {canvas}px canvas")


if __name__ == "__main__":
    main()
