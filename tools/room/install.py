"""Copies what render_all.py made (tools/room/final) into the app.

  rooms (normal + wide), sleeping covers, lit holiday overlays (trimmed, with Pal/DecoFrames.swift saying
  where each sits), the room JSONs + glass/front masks the widget fonts are built from.
Run from the repo root:  python3 tools/room/install.py
then rebuild Pal/RoomLook.swift (gen_roomlook.py) and the widget fonts (tools/build_fx_fonts.py).
"""
import json, os, shutil, glob
import numpy as np
from PIL import Image

A = "Pal/PalSprites.xcassets"
F = "tools/room/final"
T = ["sunrise", "day", "sunset", "night"]
WS = ["clear", "cloudy", "rain", "storm", "snow"]
HOLS = ["halloween", "autumn", "christmas", "newyear", "valentine"]


def save_png(img, path):
    """Lossless; a colour palette when the picture fits in 256 colours."""
    a = np.asarray(img.convert("RGBA"))
    packed = np.ascontiguousarray(a).view(np.uint32).reshape(-1)
    packed = np.where(a[..., 3].reshape(-1) == 0, 0, packed)
    uniq, idx = np.unique(packed, return_inverse=True)
    if len(uniq) <= 256:
        cols = uniq.view(np.uint8).reshape(-1, 4)
        p = Image.fromarray(idx.reshape(a.shape[:2]).astype(np.uint8), "P")
        p.putpalette(cols[:, :3].flatten().tolist())
        p.save(path, optimize=True, transparency=bytes(cols[:, 3].tolist()))
    else:
        img.save(path, optimize=True)


def imageset(name, img):
    d = f"{A}/{name}.imageset"
    shutil.rmtree(d, ignore_errors=True)
    os.makedirs(d)
    save_png(img, f"{d}/{name}.png")
    json.dump({"images": [{"filename": f"{name}.png", "idiom": "universal"}], "info": {"version": 1, "author": "xcode"},
               "properties": {"compression-type": "lossless", "preserves-vector-representation": False}},
              open(f"{d}/Contents.json", "w"), indent=2)


def main():
    rects = {}
    for t in T:
        for w in WS:
            imageset(f"room_{t}_{w}", Image.open(f"{F}/normal/room_{t}_{w}.png"))
            imageset(f"roomwide_{t}_{w}", Image.open(f"{F}/wide/room_{t}_{w}.png"))
            for b in (0, 1):
                imageset(f"covers{b}_{t}_{w}", Image.open(f"{F}/covers/covers{b}_{t}_{w}.png"))
                imageset(f"coversw{b}_{t}_{w}", Image.open(f"{F}/covers/coversw{b}_{t}_{w}.png"))
            shutil.copy(f"{F}/normal/room_{t}_{w}.json", f"tools/fx/rooms/room_{t}_{w}.json")
            for h in HOLS:
                for pre in ("deco", "decow"):
                    name = f"{pre}_{h}_{t}_{w}"
                    im = Image.open(f"{F}/deco/{name}.png").convert("RGBA")
                    bb = im.getbbox() or (0, 0, 1, 1)
                    imageset(name, im.crop(bb))                 # just the decorations, placed by DecoFrames
                    rects[name] = bb
    shutil.copy(f"{F}/normal/glass_mask.png", "tools/fx/glass_mask.png")
    shutil.copy(f"{F}/normal/front_mask.png", "tools/fx/front_mask.png")
    for h in HOLS:                                              # old flat sticker decorations + glow layers
        for suffix in ("", "_glow"):
            shutil.rmtree(f"{A}/deco_{h}{suffix}.imageset", ignore_errors=True)
    for d in glob.glob(f"{A}/chair_*.imageset") + glob.glob(f"{A}/fgplant*.imageset"):
        shutil.rmtree(d)
    lines = [f'        "{k}": CGRect(x: {b[0]}, y: {b[1]}, width: {b[2] - b[0]}, height: {b[3] - b[1]}),'
             for k, b in sorted(rects.items())]
    open("Pal/DecoFrames.swift", "w").write(
        "// Generated by tools/room/install.py: where each lit holiday overlay sits in its room (room px).\n"
        "// Each overlay is trimmed to just the decorations, so there's less to load and draw.\n"
        "import CoreGraphics\n\nenum DecoFrames {\n    static let rect: [String: CGRect] = [\n"
        + "\n".join(lines) + "\n    ]\n}\n")
    print(f"installed: 40 rooms, 160 covers, {len(rects)} holiday overlays")


if __name__ == "__main__":
    main()
