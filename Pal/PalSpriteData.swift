import Foundation

enum PalFacing { case left, right }

struct PalFrame {
    let image: String
    let ms: Int
}

struct PalClip {
    /// Which way the artwork faces before any flipping.
    let naturalFacing: PalFacing
    let frames: [PalFrame]
    /// Every frame is 68x68 with the feet on the bottom edge, so all pals share one pixel scale.
    let size: Int = 68
    var loopMs: Int { frames.reduce(0) { $0 + $1.ms } }

    /// Frame to show `t` seconds into the loop.
    func frame(at t: TimeInterval) -> PalFrame {
        var ms = Int(t * 1000) % max(loopMs, 1)
        for f in frames {
            if ms < f.ms { return f }
            ms -= f.ms
        }
        return frames[0]
    }
}

